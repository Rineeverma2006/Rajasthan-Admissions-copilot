create extension if not exists pg_trgm;

create table if not exists public.admission_knowledge (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  source_name text not null,
  source_url text not null,
  source_type text not null default 'official',
  academic_year text,
  published_at timestamptz,
  updated_at timestamptz not null default now(),
  is_published boolean not null default false,
  search_vector tsvector generated always as (
    to_tsvector('english', coalesce(title,'') || ' ' || coalesce(content,'') || ' ' || coalesce(source_name,''))
  ) stored
);
create index if not exists admission_knowledge_search_idx on public.admission_knowledge using gin(search_vector);
create index if not exists admission_knowledge_published_idx on public.admission_knowledge(is_published, updated_at desc);

create table if not exists public.college_programs (
  id bigint generated by default as identity primary key,
  college_name text not null,
  city text not null,
  branch text not null,
  counselling text not null default 'REAP',
  annual_fee numeric(12,2),
  cutoff_rank integer,
  cutoff_year integer not null,
  category text,
  quota text,
  round text,
  source_url text not null,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  constraint cutoff_rank_positive check (cutoff_rank is null or cutoff_rank > 0)
);
create index if not exists college_programs_filters_idx on public.college_programs(counselling, branch, city, cutoff_year desc);

create or replace function public.search_admission_knowledge(query_text text, match_count integer default 5)
returns table(title text, content text, source_url text, source_name text, updated_at timestamptz)
language sql stable security invoker set search_path = public
as $$
  select k.title, k.content, k.source_url, k.source_name, k.updated_at
  from public.admission_knowledge k
  where k.is_published = true
    and k.search_vector @@ websearch_to_tsquery('english', coalesce(query_text,''))
  order by ts_rank(k.search_vector, websearch_to_tsquery('english', coalesce(query_text,''))) desc, k.updated_at desc
  limit greatest(1, least(coalesce(match_count,5), 10));
$$;

alter table public.admission_knowledge enable row level security;
alter table public.college_programs enable row level security;
